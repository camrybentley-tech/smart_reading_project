/**
 * Clean a token of surrounding punctuation: quotes, commas, periods, etc.
 */
export function cleanWord(rawToken: string): string {
  return rawToken.replace(/^[^a-zA-Z0-9]+|[^a-zA-Z0-9]+$/g, '').trim();
}

/**
 * Find word detail with intelligent fallbacks (case-insensitive, lemmatization, suffix stripping)
 * Prioritizes teacher-entered keyword definition over general dictionary!
 */
export function lookupWord(rawWord: string, customStory?: Story): WordDetail {
  const cleaned = cleanWord(rawWord);
  const lower = cleaned.toLowerCase();

  // 1. Teacher-provided required keyword (from bold text or teacher list)
  if (customStory?.requiredKeywords) {
    const req = customStory.requiredKeywords.find(
      (k) => k.id.toLowerCase() === lower || k.text.toLowerCase() === lower,
    );
    if (req) {
      const dictEntry = DICTIONARY[lower];
      return {
        word: req.text || cleaned,
        baseWord: req.text || cleaned,
        ipa: req.ipa || dictEntry?.ipa || `/${lower}/`,
        partOfSpeech: req.partOfSpeech || dictEntry?.partOfSpeech || 'từ khóa bắt buộc',
        vietnameseMeaning:
          req.meaningVi || dictEntry?.vietnameseMeaning || `Từ khóa trọng tâm bài học: ${req.text || cleaned}`,
        exampleSentence:
          req.contextSentence || req.example || dictEntry?.exampleSentence || `Notice the keyword "${req.text || cleaned}" in the story.`,
        exampleTranslation: req.exampleVi || dictEntry?.exampleTranslation || '',
        isKeyword: true,
      };
    }
  }

  // 1b. Teacher-provided keyword definition ALWAYS takes high priority!
  if (customStory?.keywordDetails && customStory.keywordDetails[lower]) {
    const kw = customStory.keywordDetails[lower];
    return {
      word: cleaned,
      baseWord: kw.word,
      ipa: kw.ipa || `/${lower}/`,
      partOfSpeech: kw.partOfSpeech || 'từ khóa giáo viên chọn',
      vietnameseMeaning: kw.meaningVi,
      exampleSentence: kw.example || `Notice the word "${cleaned}" in the story.`,
      exampleTranslation: kw.exampleVi || '',
      isKeyword: true,
    };
  }

  const isStoryKeyword = customStory?.keywords
    ? customStory.keywords.map((k) => k.toLowerCase()).includes(lower)
    : customStory?.requiredKeywords
      ? customStory.requiredKeywords.some((rk) => rk.id.toLowerCase() === lower)
      : STORY_KEYWORDS.includes(lower);

  // 2. Direct dictionary match
  if (DICTIONARY[lower]) {
    const entry = DICTIONARY[lower];
    return {
      ...entry,
      isKeyword: isStoryKeyword || entry.isKeyword,
    };
  }

  // 3. Suffix stem checks
  // e.g. "whispers" -> "whisper", "readings" -> "reading"
  if (lower.endsWith('s') && DICTIONARY[lower.slice(0, -1)]) {
    const base = DICTIONARY[lower.slice(0, -1)];
    return {
      word: cleaned,
      baseWord: base.word,
      ipa: base.ipa,
      partOfSpeech: `${base.partOfSpeech} (số nhiều / ngôi thứ 3)`,
      vietnameseMeaning: base.vietnameseMeaning,
      exampleSentence: base.exampleSentence,
      exampleTranslation: base.exampleTranslation,
      isKeyword: isStoryKeyword || base.isKeyword,
    };
  }

  if (lower.endsWith('ed') && DICTIONARY[lower.slice(0, -2)]) {
    const base = DICTIONARY[lower.slice(0, -2)];
    return {
      word: cleaned,
      baseWord: base.word,
      ipa: base.ipa,
      partOfSpeech: 'động từ (quá khứ)',
      vietnameseMeaning: `đã ${base.vietnameseMeaning}`,
      exampleSentence: base.exampleSentence,
      exampleTranslation: base.exampleTranslation,
      isKeyword: isStoryKeyword || base.isKeyword,
    };
  }

  if (lower.endsWith('ing') && DICTIONARY[lower.slice(0, -3)]) {
    const base = DICTIONARY[lower.slice(0, -3)];
    return {
      word: cleaned,
      baseWord: base.word,
      ipa: base.ipa,
      partOfSpeech: 'danh động từ / hiện tại phân từ',
      vietnameseMeaning: `đang ${base.vietnameseMeaning}`,
      exampleSentence: base.exampleSentence,
      exampleTranslation: base.exampleTranslation,
      isKeyword: isStoryKeyword || base.isKeyword,
    };
  }

  // 4. Fallback for any word in a custom or pasted story
  return {
    word: cleaned,
    ipa: `/${lower}/`,
    partOfSpeech: 'từ vựng',
    vietnameseMeaning: `Từ vựng: ${cleaned}`,
    exampleSentence: `Practice pronouncing and remembering "${cleaned}".`,
    exampleTranslation: `Hãy rèn luyện phát âm và ghi nhớ từ "${cleaned}".`,
    isKeyword: isStoryKeyword,
  };
}

